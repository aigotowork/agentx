/** Focused synthetic consumer checks; independent real native acceptance lives in tests/agent_labels. */
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import puppeteer from 'puppeteer-core';
import { createLabelsFixture } from './labels.fixture.mjs';

const output = process.argv[2];
if (!output) throw new Error('Supply built management directory');
const fixture = createLabelsFixture(output);
await new Promise(resolve => fixture.server.listen(0, '127.0.0.1', resolve));
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--no-proxy-server'] });
const page = await browser.newPage();
const errors = []; page.on('pageerror', error => errors.push(error.message));
const click = async text => {
  const handle = await page.waitForFunction(text => [...document.querySelectorAll('button')].find(item => item.textContent.trim() === text && item.getClientRects().length && !item.disabled), {}, text);
  await handle.asElement().click(); await handle.dispose();
};
const fill = async (selector, value) => { await page.waitForSelector(selector, { visible: true }); await page.$eval(selector, input => { input.select(); }); await page.keyboard.press('Backspace'); if (value) await page.type(selector, value); };
const openLabels = async () => { await page.waitForSelector('.labels-disclosure'); await page.$eval('.labels-disclosure', item => { item.open = true; }); };
const pick = async name => { const row = await page.waitForFunction(name => [...document.querySelectorAll('.agent-row')].find(row => row.querySelector('strong')?.textContent === name), {}, name); await row.asElement().click(); await openLabels(); };
const openOperations = async () => { if (!await page.$('.operations-panel')) { await page.click('nav a[href="#operations"]'); await page.waitForSelector('.operations-panel'); } };
const closeOperations = async () => { if (await page.$('.operations-panel')) await click('返回工作页'); };
try {
  await page.setViewport({ width: 1280, height: 800 });
  await page.goto(`http://127.0.0.1:${fixture.server.address().port}`);
  await pick('alfa');
  assert.equal(await page.$('.labels-disclosure img'), null, 'Opaque HTML value remains text');
  await page.$eval('.agent-filter-options', element => { element.open = true; });
  await page.$eval('.label-selection', element => { element.open = true; });
  await fill('[aria-label="标签分组 key"]', 'project');
  await click('加载更多 Agent');
  await page.waitForFunction(() => document.querySelectorAll('.agent-row').length === 4);
  assert.match(await page.$eval('.agent-list', node => node.textContent), /缺失/);
  assert.match(await page.$eval('.agent-list', node => node.textContent), /未记录/);
  await fill('[aria-label="标签筛选条件"]', 'project=atlas\nplugin/state');
  await click('应用标签筛选');
  await page.waitForFunction(() => document.querySelectorAll('.agent-row').length === 1);
  const filtered = fixture.queries.find(url => url.searchParams.getAll('label').length === 2);
  assert(filtered); assert.equal(filtered.searchParams.get('current_only'), 'true'); assert.equal(filtered.searchParams.has('after'), false, 'Selector resets cursor');
  await click('清除标签筛选');
  await page.waitForFunction(() => document.querySelectorAll('.agent-row').length === 2);
  await fill('[aria-label="标签分组 key"]', '');
  await click('编辑标签');
  // Rows are sorted note, plugin/state, project.
  await fill('[aria-label="标签 value 2"]', 'approved');
  await pick('beta'); await pick('alfa');
  assert.equal(await page.$eval('[aria-label="标签 value 2"]', input => input.value), 'approved', 'Exact-ref draft survives selection');
  await click('保存标签');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('agentx.management.operations.v1') ?? '[]').some(item => item.kind === 'labels' && item.operation?.status === 'Succeeded'));
  assert.deepEqual(fixture.posts[0].body.set, { 'plugin/state': 'approved' });
  assert.equal(fixture.labels.get('alfa').project, 'atlas');
  assert.equal(fixture.posts[0].body.agent.incarnation, fixture.agents[0].incarnation);
  await closeOperations(); await openLabels();
  await page.waitForFunction(() => [...document.querySelectorAll('.label-fact')].some(item => item.textContent === 'plugin/state=approved'));
  await click('编辑标签');
  await fill('[aria-label="标签 value 2"]', 'draft-conflict');
  fixture.labels.get('alfa')['other/key'] = 'concurrent'; fixture.revisions.set('alfa', 'r99');
  await click('保存标签');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('agentx.management.operations.v1') ?? '[]').some(item => item.rejected && item.issue?.includes('revision_conflict')));
  await closeOperations(); await openLabels();
  assert.equal(await page.$eval('[aria-label="标签 value 2"]', input => input.value), 'draft-conflict', 'Conflict retains draft');
  await click('刷新并保留草稿');
  await page.waitForFunction(() => [...document.querySelectorAll('.label-row input')].some(input => input.value === 'concurrent'));
  await click('保存标签');
  await page.waitForFunction(() => document.querySelector('.context-receipt .status-label[title="Succeeded"]'));
  assert.equal(fixture.labels.get('alfa')['plugin/state'], 'draft-conflict'); assert.equal(fixture.labels.get('alfa')['other/key'], 'concurrent');
  await closeOperations(); await openLabels();
  await page.waitForFunction(() => [...document.querySelectorAll('.label-fact')].some(item => item.textContent === 'plugin/state=draft-conflict'));
  await click('编辑标签');
  await fill('[aria-label="标签 value 1"]', 'lost-result');
  fixture.state.mode = 'drop-before';
  await click('保存标签');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('agentx.management.operations.v1') ?? '[]').some(item => item.kind === 'labels' && item.missing));
  const lost = fixture.posts.at(-1);
  await page.reload(); await openLabels();
  assert.equal(await page.$eval('[aria-label="标签 value 1"]', input => input.value), 'lost-result');
  assert.equal(await page.$eval('.label-editor .label-actions button', button => button.disabled), true, 'Unknown transport result blocks new save');
  await openOperations(); await click('以原 ID 重发');
  await page.waitForFunction(() => document.querySelector('.operation-row[data-native-status="Succeeded"]'));
  assert.equal(fixture.posts.at(-1).raw, lost.raw, 'Replayed exact original identity/body');
  await closeOperations(); await openLabels();
  await page.waitForFunction(() => [...document.querySelectorAll('.label-fact')].some(item => item.textContent === 'note=lost-result'));
  await click('编辑标签');
  await fill('[aria-label="标签 value 1"]', 'unknown-result'); fixture.state.mode = 'unknown';
  await click('保存标签');
  await page.waitForFunction(() => document.querySelector('.context-receipt .status-label[title="Unknown"]'));
  await click('查看回执');
  assert(!await page.$eval('.operation-row', node => node.textContent.includes('以原 ID 重发')));
  await closeOperations(); await openLabels();
  assert.equal(await page.$eval('.label-editor .label-actions button', button => button.disabled), true);
  await page.setViewport({ width: 390, height: 844 });
  await page.$eval('.label-editor .label-actions', node => node.scrollIntoView({ block: 'nearest' }));
  assert.equal(await page.$eval('.label-editor .label-actions button', node => { const box = node.getBoundingClientRect(); const owner = node.closest('.agent-toolbar').getBoundingClientRect(); return box.top >= owner.top && box.bottom <= owner.bottom; }), true, 'Editor actions remain reachable in the toolbar viewport');
  await page.screenshot({ path: `${output}/labels-mobile.png` });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewport({ width: 1280, height: 800 });
  await page.screenshot({ path: `${output}/labels-desktop.png` });
  fixture.state.supported = false;
  await page.reload(); await openLabels();
  await page.waitForFunction(() => document.body.textContent.includes('当前服务不支持标签'));
  assert.equal(await page.$eval('.label-editor .label-actions button', button => button.disabled), true);
  assert.deepEqual(errors, []);
  process.stdout.write('PASS labels synthetic consumer: server selectors/page reset; scalar diff/plugin preservation; exact refs; draft/conflict/rebase; unknown/reload/same-ID replay; grouping missing/unknown; old-service; mobile/text safety\n');
} catch (error) {
  await writeFile(`${output}/labels-failure.json`, JSON.stringify({ error: String(error), page: await page.content(), errors, requests: fixture.queries.map(String), posts: fixture.posts }, null, 2));
  throw error;
} finally { await browser.close(); await new Promise(resolve => fixture.server.close(resolve)); }
