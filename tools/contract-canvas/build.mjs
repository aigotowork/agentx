import assert from 'node:assert/strict';
import { readFileSync, renameSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { validateModel, validateView } from './validate.mjs';

const read = url => readFileSync(url, 'utf8');
const template = read(new URL('./viewer/index.html', import.meta.url));
const layers = read(new URL('./layers.js', import.meta.url));
const relativeURL = (path, label) => {
  assert(/^(?:[\w.-]+\/)*[\w.-]+$/.test(path) && !path.startsWith('/'), `${label} must be a relative static path`);
  return path;
};
// Keep data in a quoted JSON string; even an HTML parser cannot see a script end tag.
const scriptJSON = data => JSON.stringify(JSON.stringify(data))
  .replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026')
  .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

/** Derive the two static entry artifacts after validating both authored inputs. */
export function prepare(model, view, { viewerPath, dataPath }) {
  const index = validateModel(model);
  validateView(model, view, index);
  return {
    index,
    html: '<!-- Generated by Contract Canvas from its viewer template. Do not edit. -->\n' +
      template.replaceAll('@VIEWER@', relativeURL(viewerPath, 'viewer path')).replace('@DATA@', relativeURL(dataPath, 'data path')),
    script: '/* Generated by Contract Canvas from model + view JSON. Do not edit. */\n' +
      `globalThis.CONTRACT_MODEL = JSON.parse(${scriptJSON(model)});\n` +
      `globalThis.CONTRACT_VIEW = JSON.parse(${scriptJSON(view)});\n` + layers,
  };
}

/** Compare artifacts or replace changed files atomically (data first, entry last). */
export function publish(page, { index, data, write = false }) {
  for (const [path, content] of [[data, page.script], [index, page.html]]) {
    let previous;
    try { previous = read(path); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (previous === content) continue;
    assert(write, `stale or missing ${path}; regenerate the static entry`);
    const temp = `${path}.${process.pid}.tmp`;
    writeFileSync(temp, content);
    renameSync(temp, path);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const [, , directory, viewerPath, mode] = process.argv;
    assert(directory && viewerPath && (mode === undefined || mode === '--write'), 'Usage: node build.mjs <project directory> <viewer URL relative to its index> [--write]');
    const load = name => JSON.parse(read(resolve(directory, name)));
    const page = prepare(load('model.json'), load('view.json'), { viewerPath, dataPath: 'data.js' });
    publish(page, { index: resolve(directory, 'index.html'), data: resolve(directory, 'data.js'), write: mode === '--write' });
    console.log(`Contract Canvas: ${directory} artifacts ${mode ? 'ready' : 'verified'}.`);
  } catch (error) {
    console.error(`Contract Canvas: ${error.message}`);
    process.exitCode = 1;
  }
}
