/** Consumer checkpoints and isolation for the reusable pure core. */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const root = new URL('../', import.meta.url);
const runtime = JSON.parse(await readFile(new URL('.docs/architecture/runtime-atlas/model.json', root), 'utf8'));
const request = JSON.parse(await readFile(new URL('tools/flow-atlas/examples/request.json', root), 'utf8'));
const script = await readFile(new URL('tools/flow-atlas/core.js', root), 'utf8');
const context = vm.createContext({});
vm.runInContext(script, context);
const core = context.FlowAtlas;
const original = JSON.stringify(request);
const initial = core.fold(request, 'read-record', -1);
const reading = core.fold(request, 'read-record', 1);
assert.equal(initial.nodes.archive.tone, 'stored');
assert.equal(reading.nodes.archive.tone, 'busy');
assert.equal(reading.nodes.archive.label, '条目已保存', 'Partial tone patch retains its original label');
const diff = core.changes(request, 'read-record', 1).find(item => item.id === 'archive');
assert.equal(diff.before, diff.after);
assert.equal(diff.beforeTone, 'stored');
assert.equal(diff.afterTone, 'busy');
const completed = core.fold(request, 'read-record', 3);
assert.equal(completed.facts.response, '200 · 条目 42');
assert.equal(completed.nodes.catalog.label, '空闲');
assert.equal(completed.nodes.archive.tone, 'stored');
reading.nodes.archive.label = 'mutated consumer';
reading.facts.response = 'mutated consumer';
assert.equal(initial.nodes.archive.label, '条目已保存');
assert.equal(completed.nodes.archive.label, '条目已保存');
assert.equal(JSON.stringify(request), original);
for (const index of [-2, 1.5, request.scenarios[0].steps.length]) assert.throws(() => core.fold(request, 'read-record', index), /checkpoint/);
assert.throws(() => core.fold(request, 'missing', 0), /Unknown scenario/);
const disconnected = core.fold(runtime, 'appserver-disconnect', 3);
assert.equal(disconnected.nodes.bridge.tone, 'stopped');
assert.notEqual(disconnected.nodes.codex.tone, 'stopped');
assert.equal(disconnected.nodes.thread.tone, 'unknown');
const detached = core.fold(runtime, 'headless-close', 1);
assert.equal(detached.nodes.terminal.tone, 'stopped');
assert.equal(detached.nodes.pty.tone, 'running');
assert.match(core.fold(runtime, 'appserver-mail', 0).facts.inbox, /待收/);
assert.match(core.fold(runtime, 'appserver-mail', 3).facts.inbox, /Issuing/);
assert.match(core.fold(runtime, 'appserver-mail', 5).facts.inbox, /确认/);
console.log('PASS: unrelated checkpoint values, partial/tone-only patches, snapshot/model isolation, invalid checkpoints, runtime continuity/receipt boundaries');
