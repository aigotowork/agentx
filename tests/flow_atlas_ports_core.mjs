/** Independently consume resolved calls, effects, isolation and presentation stages. */
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const root = new URL('../', import.meta.url);
const model = JSON.parse(await readFile(new URL('tools/flow-atlas/examples/request.json', root), 'utf8'));
const runtime = JSON.parse(await readFile(new URL('.docs/architecture/runtime-atlas/model.json', root), 'utf8'));
const context = vm.createContext({});
for (const file of ['core.js','viewer/ports.js']) vm.runInContext(await readFile(new URL('tools/flow-atlas/' + file, root), 'utf8'), context);
const { FlowAtlas: core, FlowAtlasPorts: presentation } = context;
const original = JSON.stringify(model);
const accepted = core.calls(model, 'read-record', 4)[0];
assert.equal(accepted.from.id, 'visitor');
assert.equal(accepted.target.id, accepted.port.nodeId);
assert.equal(accepted.result.kind, 'accepted');
assert.equal(accepted.responseBeat, 2);
assert.equal(accepted.effects.find(e => e.target === 'node' && e.id === 'catalog').kind, 'change');
const statuses = [presentation.status(accepted,'ready',-1), presentation.status(accepted,'flow',0), presentation.status(accepted,'flow',1), presentation.status(accepted,'flow',2), presentation.status(accepted,'handling',-1), presentation.status(accepted,'applied',-1)];
assert.equal(statuses.map(s => s.stage).join(','), 'planned,calling,waiting,returning,waiting,accepted');
assert.equal(statuses.filter(s=>s.known).length,1);
accepted.input.recordId='mutated'; accepted.port.input[0].name='mutated'; accepted.from.label='mutated'; accepted.effects[0].after='mutated'; accepted.result.summary='mutated';
assert.equal(JSON.stringify(model), original);
assert.notEqual(core.calls(model,'read-record',4)[0].input.recordId,'mutated');
const unknown = core.calls(model,'unknown-selection',0)[0];
assert.equal(unknown.result.kind,'unknown');
assert.equal('responseBeat' in unknown,false);
assert(unknown.effects.every(e=>e.kind==='observation'));
assert.equal(core.calls(model,'reject-selection',0)[0].result.kind,'rejected');
assert.equal(core.calls(model,'read-record',-1).length,0);
assert.throws(()=>core.calls(model,'read-record',-2),/checkpoint/);
assert.throws(()=>core.calls(model,'missing',0),/Unknown scenario/);
const issue = core.calls(runtime,'appserver-mail',3)[0];
assert.equal(issue.result.kind,'unknown');
assert.equal(issue.effects.find(e=>e.id==='inbox').after,'Issuing · 结果尚未确认');
assert.equal(core.calls(runtime,'appserver-mail',4)[0].effects.length,0);
const confirmation=core.calls(runtime,'appserver-mail',5)[0];
assert.equal(confirmation.result.kind,'accepted');
assert.equal(confirmation.effects.find(e=>e.id==='inbox').after,'本批次交付已确认');
const close=core.calls(runtime,'appserver-disconnect',1)[0];
assert.equal(close.port.label,'ReleaseNativeRoot');
assert(!close.effects.some(e=>e.id==='codex'));
console.log('PASS: resolved method/outcome/effect, presentation stages, returned-object isolation, rejection/unknown and exact runtime receipt boundaries');
